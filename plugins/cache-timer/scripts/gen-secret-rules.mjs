// Regenerates hooks/secret-rules.ts from gitleaks' rule file (MIT, see THIRD_PARTY_NOTICES.md).
//   node scripts/gen-secret-rules.mjs                 fetch the rules from the gitleaks repo
//   node scripts/gen-secret-rules.mjs path/to.toml    use a local copy
// Go's regex flavour is close to JavaScript's. What differs: `(?P<name>` is `(?<name>`, `\z` and `\A` are `$` and `^`, POSIX
// classes such as `[[:alnum:]]` (which JavaScript reads, without an error, as a set of the characters `[:alnum` then a `]`) are
// spelled out, and a
// `(?i)` flag, which JavaScript allows only as a flag on the whole pattern: a rule that has one is matched case-insensitively
// throughout (it can only match a little more, never less).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const URL = 'https://raw.githubusercontent.com/gitleaks/gitleaks/master/config/gitleaks.toml'
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'hooks', 'secret-rules.ts')
const toml = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(URL)).text()

// Rules left out because crafted text makes them take seconds (their time grows much faster than the text, and a hooks module
// blocks the session while it runs). The first five are vendor tokens that are rarely seen; the curl ones are covered by
// redact()'s own linear patterns (Authorization headers, bearer tokens, and `-u user:password`).
const SLOW = new Set(['cisco-meraki-api-key', 'cohere-api-token', 'okta-access-token', 'sumologic-access-id', 'privateai-api-token', 'curl-auth-user', 'curl-auth-header'])

// Go's POSIX classes (ASCII only), as the ranges they stand for inside a bracket expression.
const POSIX = {
  alnum: '0-9A-Za-z', alpha: 'A-Za-z', digit: '0-9', lower: 'a-z', upper: 'A-Z', xdigit: '0-9A-Fa-f', word: '0-9A-Za-z_',
  space: '\\t\\n\\v\\f\\r ', blank: '\\t ', punct: '!-\\/:-@\\[-`{-~', cntrl: '\\x00-\\x1f\\x7f', print: ' -~', graph: '!-~', ascii: '\\x00-\\x7f',
}

const rules = []
for (const block of toml.split(/^\[\[rules\]\]$/m).slice(1)) {
  const id = block.match(/^id = "([^"]+)"/m)?.[1]
  const regex = block.match(/^regex = '''([\s\S]*?)'''/m)?.[1]
  if (!id || !regex) continue // a rule that matches on a file path only
  if (SLOW.has(id)) continue
  let source = regex.replace(/\(\?P</g, '(?<').replace(/\\z/g, '$').replace(/\\A/g, '^').replace(/\[:(\w+):\]/g, (all, name) => {
    if (!(name in POSIX)) throw new Error(`${id}: no translation for the POSIX class ${all}`)
    return POSIX[name]
  })
  let flags = 'g'
  const lead = source.match(/^\(\?([a-z]+)\)/)
  if (lead) {
    source = source.slice(lead[0].length)
    for (const c of lead[1]) if ('ism'.includes(c) && !flags.includes(c)) flags += c
  }
  if (/\(\?i\)/.test(source)) {
    source = source.replace(/\(\?i\)/g, '')
    if (!flags.includes('i')) flags += 'i'
  }
  try {
    new RegExp(source, flags)
  } catch (err) {
    console.error(`skipped ${id}: ${err.message}`)
    continue
  }
  const entropy = Number(block.match(/^entropy = ([\d.]+)/m)?.[1] ?? 0)
  const group = Number(block.match(/^secretGroup = (\d+)/m)?.[1] ?? 0)
  const keywords = (block.match(/^keywords = \[([^\]]*)\]/m)?.[1] ?? '').split(',').map(s => s.trim().replace(/^"|"$/g, '')).filter(Boolean)
  rules.push([id, source, flags, entropy, group, keywords])
}

writeFileSync(out, `// Generated by scripts/gen-secret-rules.mjs from the gitleaks rule file: do not edit. ${rules.length} rules.
// gitleaks is MIT licensed, Copyright (c) 2019 Zachary Rice. See THIRD_PARTY_NOTICES.md.
// Each rule: [id, regex source, flags, minimum entropy of the secret (0: none), secret group (0: the first capture group, else the match), keywords that must appear for the rule to run].
export type SecretRule = [id: string, source: string, flags: string, entropy: number, group: number, keywords: string[]]

export const SECRET_RULES: SecretRule[] = [
${rules.map(r => '  ' + JSON.stringify(r)).join(',\n')},
]
`)
console.log(`wrote ${rules.length} rules to ${out}`)
